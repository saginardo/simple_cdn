type TranslationKey = keyof typeof english;
type Variables = Record<string, string | number>;

function storedLocale(): Locale {
  if (typeof window === "undefined") return "zh-CN";
  try {
    return window.localStorage.getItem(localeStorageKey) === "en"
      ? "en"
      : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

let activeLocale: Locale = storedLocale();

function interpolate(value: string, variables?: Variables) {
  if (!variables) return value;
  return value.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in variables ? String(variables[key]) : match,
  );
}

export function t(key: TranslationKey | string, variables?: Variables) {
  const leading = key.match(/^\s*/)?.[0] ?? "";
  const trailing = key.match(/\s*$/)?.[0] ?? "";
  const normalizedKey = key.trim();
  const translated =
    activeLocale === "en"
      ? english[normalizedKey as TranslationKey]
      : undefined;
  return `${leading}${interpolate(translated ?? normalizedKey, variables)}${trailing}`;
}

export function getLocale() {
  return activeLocale;
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: typeof t;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => activeLocale);
  const setLocale = useCallback((nextLocale: Locale) => {
    activeLocale = nextLocale;
    try {
      window.localStorage.setItem(localeStorageKey, nextLocale);
    } catch {
      // The active session can still switch locales when storage is unavailable.
    }
    setLocaleState(nextLocale);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
